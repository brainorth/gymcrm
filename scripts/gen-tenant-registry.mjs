#!/usr/bin/env node
/**
 * Generates src/server/db/tenant-registry.ts from prisma/schema.prisma.
 *
 * Why generated? The tenant guard must know, for every model, whether it is
 * tenant-owned and which column carries the tenant key. Hand-maintaining that
 * list is how isolation bugs are born. `npm run test:registry` fails if this
 * file is stale, so a new model can never silently slip past the guard.
 *
 * Classification rule (matches the schema's hard rules):
 *   - has a `gymId` field  -> tenant-owned, scoped by gymId
 *   - is `Gym`             -> tenant-owned, scoped by id
 *   - anything else        -> PLATFORM ONLY (denied on the tenant client)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = readFileSync(path.join(root, "prisma/schema.prisma"), "utf8");

/**
 * Cross-cutting tables with a NULLABLE gymId (platform actions have no tenant).
 * They are written by dedicated services that take gymId explicitly, so the
 * tenant client must not reach them — otherwise `gymId: null` rows (other gyms'
 * audit trails, reset tokens) become visible.
 */
const FORCE_PLATFORM = new Set([
  "VerificationToken",
  "AuditLog",
  "NotificationOutbox",
]);

const enums = new Set(
  [...schema.matchAll(/^enum\s+(\w+)\s*\{/gm)].map((m) => m[1]),
);
const modelBlocks = [...schema.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm)].map(
  (m) => ({ name: m[1], body: m[2] }),
);
const modelNames = new Set(modelBlocks.map((m) => m.name));

const models = modelBlocks.map(({ name, body }) => {
  const fields = [];
  for (const rawLine of body.split("\n")) {
    const line = rawLine.replace(/\/\/.*$/, "").trim();
    if (!line || line.startsWith("@@") || line.startsWith("//")) continue;
    const match = /^(\w+)\s+([\w[\]?]+)/.exec(line);
    if (!match) continue;
    const [, fieldName, rawType] = match;
    const type = rawType.replace(/[\[\]?]/g, "");
    fields.push({ name: fieldName, type, isList: rawType.includes("[]") });
  }
  const relations = {};
  const jsonFields = [];
  for (const f of fields) {
    if (modelNames.has(f.type)) relations[f.name] = f.type;
    else if (f.type === "Json") jsonFields.push(f.name);
    else if (enums.has(f.type)) continue;
  }
  const hasGymId = fields.some((f) => f.name === "gymId");
  const scope = FORCE_PLATFORM.has(name)
    ? null
    : hasGymId
      ? "gymId"
      : name === "Gym"
        ? "id"
        : null;
  return { name, scope, relations, jsonFields };
});

const tenant = models.filter((m) => m.scope);
const platform = models.filter((m) => !m.scope);

const render = (m) => {
  const rel = Object.entries(m.relations)
    .map(([k, v]) => `      ${k}: "${v}",`)
    .join("\n");
  const json = m.jsonFields.map((f) => `"${f}"`).join(", ");
  return `  ${m.name}: {
    scope: "${m.scope}",
    jsonFields: [${json}],
    relations: {
${rel}
    },
  },`;
};

const out = `// AUTO-GENERATED by scripts/gen-tenant-registry.mjs — DO NOT EDIT BY HAND.
// Run \`npm run gen:tenant-registry\` after changing prisma/schema.prisma.

export type TenantScopeColumn = "gymId" | "id";

export type TenantModelMeta = {
  scope: TenantScopeColumn;
  /** Fields whose value is arbitrary JSON — never scanned for nested writes. */
  jsonFields: readonly string[];
  /** relation field -> target model */
  relations: Readonly<Record<string, string>>;
};

/** Models the tenant-scoped client is allowed to touch. Fail-closed: unlisted = denied. */
export const TENANT_MODELS = {
${tenant.map(render).join("\n")}
} as const satisfies Record<string, TenantModelMeta>;

export type TenantModelName = keyof typeof TENANT_MODELS;

/** Identity / platform-billing / infrastructure tables: platform client only. */
export const PLATFORM_MODELS = [
${platform.map((m) => `  "${m.name}",`).join("\n")}
] as const;

export const ALL_MODELS = [
${models.map((m) => `  "${m.name}",`).join("\n")}
] as const;

export function isTenantModel(model: string): model is TenantModelName {
  return Object.hasOwn(TENANT_MODELS, model);
}

export function tenantMeta(model: string): TenantModelMeta | undefined {
  return isTenantModel(model) ? TENANT_MODELS[model] : undefined;
}
`;

writeFileSync(path.join(root, "src/server/db/tenant-registry.ts"), out);
console.log(
  `tenant-registry: ${tenant.length} tenant models, ${platform.length} platform models`,
);
